#!/usr/bin/env bun
/** One inventory -> runtime themes, Tailwind registrations, utilities, and documentation. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { format } from 'oxfmt'
import { entries, themeValues, utilityClasses } from '../src/styles/tokens/model'
import { themes } from '../src/styles/tokens/themes'
import { componentRecipes } from '../src/styles/tokens/recipes'
import { createPresetCSS } from '../src/styles/tokens/preset'
import { validateTokenSystem } from './validate-tokens'

const errors = validateTokenSystem()
if (errors.length) throw new Error(errors.join('\n'))
const root = join(import.meta.dir, '..')
const check = process.argv.includes('--check')
const options = JSON.parse(readFileSync(join(root, '.oxfmtrc.json'), 'utf8'))
const header =
	'/* Generated by bun run generate:tokens. Edit src/styles/tokens/definitions.ts. */\n'
const declarations = (values: Record<string, string>) =>
	Object.entries(values)
		.map(([name, value]) => `${name}: ${value};`)
		.join('\n')
const native = entries.filter(([, token]) => token.category === 'foundation')
const aliases = entries.flatMap(([name, token]) =>
	token.tailwind.map((alias) => `${alias}: var(${name});`),
)
const publicUtilities = entries.flatMap(([name, token]) =>
	Object.entries(token.utilities).map(([className, properties]) => ({
		name,
		className,
		properties,
	})),
)
const recipes = Object.entries(componentRecipes)
	.map(
		([name, recipe]) =>
			`@utility ${name} {\n${declarations(Object.fromEntries(Object.entries(recipe).map(([key, value]) => [key.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()), value])))}\n}`,
	)
	.join('\n')
const adapter =
	header +
	`@theme static {\n${native.map(([name]) => `${name}: ${themeValues('default', 'light')[name]};`).join('\n')}\n}\n@theme inline {\n${aliases.join('\n')}\n}\n` +
	publicUtilities
		.map(({ className, properties }) => `@utility ${className} {\n${declarations(properties)}\n}`)
		.join('\n') +
	'\n' +
	recipes
const outputs: Record<string, string> = {
	'src/styles/tokens/utility-aliases.ts':
		"// Generated by bun run generate:tokens. Edit definitions.ts.\nimport type { TokenName } from './model'\nexport const componentUtilityAliases = " +
		JSON.stringify(
			Object.fromEntries(
				entries
					.filter(([, token]) => ['component', 'system'].includes(token.category))
					.flatMap(([name, token]) => token.tailwind.map((alias) => [alias, name])),
			),
			null,
			2,
		) +
		' as const satisfies Record<string, TokenName>\n',
	'src/styles/tokens/tailwind-public-utilities.css': adapter,
	'src/styles/tokens/semantic-utilities.css':
		header +
		'@layer utilities {\n' +
		publicUtilities
			.map(({ className, properties }) => `.${className} {\n${declarations(properties)}\n}`)
			.join('\n') +
		'\n}',
	'src/styles/tokens/compat.css':
		header +
		':root, .dark, [data-preset], [data-theme] {\n' +
		entries
			.flatMap(([name, token]) => token.compat.map((alias) => `${alias}: var(${name});`))
			.join('\n') +
		'\n}\n@theme inline {\n' +
		entries
			.flatMap(([name, token]) =>
				token.compat.map((alias) => `--color-${alias.slice(2)}: var(${name});`),
			)
			.join('\n') +
		'\n}',
}
for (const theme of themes) {
	const scope = `[data-preset="${theme.name}"]`
	outputs[`src/styles/presets/${theme.name}.css`] =
		header +
		createPresetCSS({
			light: themeValues(theme.name, 'light'),
			dark: themeValues(theme.name, 'dark'),
		})
			.replace(':root {', `:root, ${scope} {`)
			.replace('.dark {', `.dark, ${scope}.dark, .dark ${scope} {`)
}
const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ')
outputs['docs/token-reference.md'] =
	'# Token reference\n\nGenerated from the single `tokens` record in `src/styles/tokens/definitions.ts`. Every row owns complete values for all eight themes. [Authoring and enforcement](tokens.md).\n\n' +
	[...new Set(entries.map(([, token]) => token.group))]
		.map(
			(group) =>
				`## ${group}\n\n| Token | Purpose | Utility classes (examples) | Default light | Default dark |\n| --- | --- | --- | --- | --- |\n` +
				entries
					.filter(([, token]) => token.group === group)
					.map(
						([name, token]) =>
							`| \`${name}\` | ${cell(token.description)} | ${
								utilityClasses(name, token)
									.map((v) => `\`${v}\``)
									.join(', ') || 'CSS variable'
							} | \`${cell(themeValues('default', 'light')[name])}\` | \`${cell(themeValues('default', 'dark')[name])}\` |`,
					)
					.join('\n'),
		)
		.join('\n\n') +
	'\n'
outputs['skills/use-composables/references/semantic-utilities.md'] =
	'# Public semantic utility manifest\n\nGenerated from `src/styles/tokens/definitions.ts`. These classes ship in styles.css without Tailwind.\n\n| Class | Token | CSS |\n| --- | --- | --- |\n' +
	publicUtilities
		.map(
			({ name, className, properties }) =>
				`| \`${className}\` | \`${name}\` | \`${declarations(properties).replaceAll('\n', ' ')}\` |`,
		)
		.join('\n') +
	'\n'
let failed = false
for (const [path, source] of Object.entries(outputs)) {
	const full = join(root, path)
	const result = await format(full, source, options)
	if (result.errors.length) throw new Error(JSON.stringify(result.errors))
	if (check) {
		if (!existsSync(full) || readFileSync(full, 'utf8') !== result.code) {
			console.error(`Stale generated file: ${path}`)
			failed = true
		}
	} else writeFileSync(full, result.code)
}
if (failed) process.exit(1)
console.log(
	`${check ? 'Verified' : 'Generated'} ${Object.keys(outputs).length} files from ${entries.length} tokens.`,
)
