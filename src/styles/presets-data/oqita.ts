// Neutral status surfaces keep larger areas calm. Saturated fills remain available
// for deliberate brand accents; labels retain their semantic colour.
function colourRoles(
	surface: string,
	roles: Record<string, { fill: string; text: string }>,
): Record<string, string> {
	return Object.fromEntries(
		Object.entries(roles).flatMap(([role, { fill, text }]) => [
			[`--bg-surface-${role}`, surface],
			[`--bg-fill-${role}`, fill],
			[`--text-${role}`, text],
			[`--icon-${role}`, text],
			[`--border-${role}`, surface],
		]),
	)
}

